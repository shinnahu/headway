/** A piece of a message (the reason after a colon) in Spanish, or as it came. */
function piece(text) {
  if (ES_MESSAGES[text]) return ES_MESSAGES[text];
  for (const [pattern, render] of ES_ERRORS) {
    const m = pattern.exec(text);
    if (m) return render(m);
  }
  return text;
}

